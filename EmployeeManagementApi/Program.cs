
using EmployeeManagementApi.Data;
using EmployeeManagementApi.Middleware;
using EmployeeManagementApi.Services;
using Microsoft.EntityFrameworkCore;
using Microsoft.OpenApi;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.IdentityModel.Tokens;
using System.Text;

namespace EmployeeManagementApi
{
    public class Program
    {
        public static void Main(string[] args)
        {
            var builder = WebApplication.CreateBuilder(args);

            // Add services to the container.

            builder.Services.AddControllers();
            // Learn more about configuring OpenAPI at https://aka.ms/aspnet/openapi
            builder.Services.AddOpenApi();
            
            //Add the DBContext to the services collection, so that it can be injected into the controllers. 
            builder.Services.AddDbContext<EmployeeDbContext>(options => options.UseSqlServer(builder.Configuration.GetConnectionString("DefaultConnection"))); 
            //This line adds the EmployeeDbContext to the services collection, so that it can be injected into the controllers. The UseSqlServer method is used to configure the DbContext to use SQL Server as the database provider. The connection string is retrieved from the appsettings.json file using the GetConnectionString method.)

            builder.Services.AddScoped<IEmployeeService, EmployeeService>();//This line adds the EmployeeService to the services collection, so that it can be injected into the controllers. The AddScoped method is used to configure the service to be created once per request.
            builder.Services.AddEndpointsApiExplorer(); //This line adds the Endpoints API Explorer to the services collection, so that it can be used to generate the OpenAPI documentation. The Endpoints API Explorer is used to discover the endpoints in the application and generate the OpenAPI documentation.

            //Since SwashBuckle has migrated to Microsoft.OpenApi 2.x, there is a change in the way to add the Swagger generator to the services collection. The AddSwaggerGen method is no longer available and has been replaced with the AddSwaggerGen method in the Microsoft.OpenApi namespace. The AddSwaggerGen method is used to configure the Swagger generator to generate the OpenAPI documentation based on the endpoints discovered by the Endpoints API Explorer.
            builder.Services.AddSwaggerGen(options =>
            {
                options.SwaggerDoc("v1", new OpenApiInfo
                {
                    Title = "Employee Management API Documentation",
                    Version = "v1",
                    Description = "API for managing employees in the LTTS organization.",
                }); //This line adds the Swagger generator to the services collection, so that it can be used to generate the OpenAPI documentation. The Swagger generator is used to generate the OpenAPI documentation based on the endpoints discovered by the Endpoints API Explorer.
            });

            //////////////////////Jwt Authentication//////////////////////////
            var jwtSettings = builder.Configuration.GetSection("Jwt");
            var secretKey = jwtSettings.GetValue<string>("SecretKey")?? throw new InvalidOperationException("SecretKey is not configured in appsettings.json");
            var signingKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(secretKey));

            builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme)
                .AddJwtBearer(options =>
                {
                    options.TokenValidationParameters = new TokenValidationParameters
                    {
                        ValidateIssuer = true,
                        ValidateAudience = true,
                        ValidateLifetime = true,
                        ValidateIssuerSigningKey = true,
                        ValidIssuer = jwtSettings.GetValue<string>("Issuer"),
                        ValidAudience = jwtSettings.GetValue<string>("Audience"),
                        IssuerSigningKey = signingKey
                    };
                });
            builder.Services.AddAuthorization();
            //////////////////////////////////////////////////////////////////


            var app = builder.Build(); //After this line, no more adding of middleware or services is allowed. This line builds the application and prepares it to handle requests.

            // Configure the HTTP request pipeline.
            if(app.Environment.IsDevelopment())
            {
                app.UseSwagger(); //This line adds the Swagger middleware to the request pipeline, so that it can be used to generate the OpenAPI documentation. The Swagger middleware is used to serve the OpenAPI documentation generated by the Swagger generator.
                app.UseSwaggerUI(); //This line adds the Swagger UI middleware to the request pipeline, so that it can be used to display the OpenAPI documentation in a web browser. The Swagger UI middleware is used to serve the Swagger UI, which is a web-based user interface for exploring and testing the API endpoints.
            }
            app.UseMiddleware<GlobalExceptionMiddleware>(); //Add the global exception middleware to the pipeline.
            app.UseAuthentication();
            app.UseAuthorization();
            app.MapControllers();

            app.Run();
        }
    }
}
